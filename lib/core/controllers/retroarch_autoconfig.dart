/// Generates a RetroArch input autoconfig (`.cfg`) from a GAMEBOX profile.
///
/// RetroArch's Android input driver identifies buttons by Android key code,
/// so key bindings translate directly. RetroPad naming differs from the
/// Android/Xbox layout: RetroPad `b` is the bottom face button (Android A),
/// `a` the right one (Android B), `y` the left (Android X), `x` the top
/// (Android Y).
///
/// Axis bindings are deliberately NOT exported: RetroArch's Android axis
/// numbering is not the Android AXIS_* constant, and a wrong value would
/// silently break the pad. Users keep RetroArch's own analog defaults.
library;

import 'controller_profile.dart';

const Map<PadAction, String> _retroPadNames = {
  PadAction.a: 'b',
  PadAction.b: 'a',
  PadAction.x: 'y',
  PadAction.y: 'x',
  PadAction.l1: 'l',
  PadAction.r1: 'r',
  PadAction.l2: 'l2',
  PadAction.r2: 'r2',
  PadAction.l3: 'l3',
  PadAction.r3: 'r3',
  PadAction.start: 'start',
  PadAction.select: 'select',
  PadAction.dpadUp: 'up',
  PadAction.dpadDown: 'down',
  PadAction.dpadLeft: 'left',
  PadAction.dpadRight: 'right',
};

String _quote(String s) => s.replaceAll('"', "'").replaceAll('\n', ' ');

String retroArchAutoconfig({
  required String deviceName,
  int? vendorId,
  int? productId,
  required ControllerProfile profile,
}) {
  final b = StringBuffer()
    ..writeln('# Generated by GAMEBOX — experimental, review before use.')
    ..writeln('# Copy into RetroArch\'s autoconfig/android directory.')
    ..writeln('# Analog axes are not exported; RetroArch defaults apply.')
    ..writeln('# GAMEBOX dead zone ${profile.deadZone.toStringAsFixed(2)}, '
        'trigger threshold ${profile.triggerThreshold.toStringAsFixed(2)}.')
    ..writeln('input_driver = "android"')
    ..writeln('input_device = "${_quote(deviceName)}"');
  if (vendorId != null) b.writeln('input_vendor_id = "$vendorId"');
  if (productId != null) b.writeln('input_product_id = "$productId"');
  for (final action in PadAction.values) {
    final binding = profile.bindings[action];
    // Unmapped actions use the standard Android code the pad reports.
    final code = binding == null ? action.standardKeyCode : binding.keyCode;
    if (code == null) {
      b.writeln('# ${action.label}: bound to an axis in GAMEBOX — not exported');
      continue;
    }
    b.writeln('input_${_retroPadNames[action]}_btn = "$code"');
  }
  return b.toString();
}

/// File-name-safe version of a controller name.
String autoconfigFileName(String deviceName) {
  final safe = deviceName.replaceAll(RegExp(r'[^A-Za-z0-9 _\-]'), '').trim().replaceAll(RegExp(r'\s+'), '_');
  return '${safe.isEmpty ? 'controller' : safe}.cfg';
}
